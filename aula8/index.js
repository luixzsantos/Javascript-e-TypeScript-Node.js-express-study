// ECMAScript 2015 (ES6) - let e const

// Variáveis criadas com var tem escopo global ou de função, enquanto let e const tem escopo de bloco
// Variáveis criadas com var podem ser redeclaradas e atualizadas, enquanto let pode ser atualizada mas não redeclarada, e const não pode ser nem atualizada nem redeclarada
let nome = 'Luiz';
let sobrenome = ' Otávio';

console.log(`meu nome é, ${nome} ${sobrenome}`);
